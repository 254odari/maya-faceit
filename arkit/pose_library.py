class SearchEngine:
    """
    Implements search and filtering functionality.
    """
    def __init__(self, registry: PoseRegistry):
        self._registry = registry

    def search(self, query: str) -> List[PoseEntry]:
        """
        Search by name (substring), tags, category, author, and channel names.
        Case-insensitive partial match.
        """
        query_lower = query.lower()
        results = []
        for entry in self._registry.get_all():
            # Search name
            if query_lower in entry.metadata.name.lower():
                results.append(entry)
                continue
            # Search tags
            for tag in entry.metadata.tags:
                if query_lower in tag.lower():
                    results.append(entry)
                    break
            if entry in results:
                continue
            # Search category
            if query_lower in entry.metadata.category.lower():
                results.append(entry)
                continue
            # Search author
            if query_lower in entry.metadata.author.lower():
                results.append(entry)
                continue
            # Search channel names (key in coefficients)
            for ch in entry.pose.coefficients.keys():
                if query_lower in ch.lower():
                    results.append(entry)
                    break
        return results

    def filter_by_tags(self, tags: List[str], match_all: bool = True) -> List[PoseEntry]:
        """Filter poses that have all (or any) of the given tags."""
        if not tags:
            return self._registry.get_all()
        results = []
        for entry in self._registry.get_all():
            entry_tags = set(entry.metadata.tags)
            if match_all:
                if all(tag in entry_tags for tag in tags):
                    results.append(entry)
            else:
                if any(tag in entry_tags for tag in tags):
                    results.append(entry)
        return results

    def filter_by_category(self, category: str) -> List[PoseEntry]:
        """Filter poses by exact category match."""
        return [e for e in self._registry.get_all() if e.metadata.category == category]

    def filter_by_author(self, author: str) -> List[PoseEntry]:
        return [e for e in self._registry.get_all() if e.metadata.author == author]

    def filter_by_channels(self, channels: List[str], min_value: float = 0.01) -> List[PoseEntry]:
        """Filter poses that have at least one of the given channels with value > min_value."""
        channel_set = set(channels)
        results = []
        for entry in self._registry.get_all():
            for ch in entry.pose.coefficients:
                if ch in channel_set and entry.pose.coefficients[ch] > min_value:
                    results.append(entry)
                    break
        return results

    def filter_by_favorite(self) -> List[PoseEntry]:
        return [e for e in self._registry.get_all() if e.metadata.favorite]

    def filter_by_source(self, source: str) -> List[PoseEntry]:
        return [e for e in self._registry.get_all() if e.metadata.source == source]

    def filter_by_date_range(self, start: Optional[str] = None, end: Optional[str] = None) -> List[PoseEntry]:
        """Filter by creation/modification date range (ISO strings)."""
        results = []
        for entry in self._registry.get_all():
            if start and entry.metadata.created < start:
                continue
            if end and entry.metadata.created > end:
                continue
            results.append(entry)
        return results


