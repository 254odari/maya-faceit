@dataclass
class PoseMetadata:
    """
    Metadata for a pose entry.
    """
    id: str
    name: str
    created: str  # ISO timestamp
    modified: str  # ISO timestamp
    author: str = "unknown"
    tags: List[str] = field(default_factory=list)
    category: str = "Uncategorized"
    favorite: bool = False
    version: int = 1
    source: str = "user"  # "builtin" or "user"
    notes: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> PoseMetadata:
        # Ensure required fields
        return cls(
            id=data.get("id", str(uuid.uuid4())),
            name=data.get("name", "Unnamed"),
            created=data.get("created", datetime.utcnow().isoformat()),
            modified=data.get("modified", datetime.utcnow().isoformat()),
            author=data.get("author", "unknown"),
            tags=data.get("tags", []),
            category=data.get("category", "Uncategorized"),
            favorite=data.get("favorite", False),
            version=data.get("version", 1),
            source=data.get("source", "user"),
            notes=data.get("notes", ""),
        )

    def touch(self):
        """Update modification timestamp."""
        self.modified = datetime.utcnow().isoformat()
        self.version += 1


@dataclass
class PoseEntry:
    """
    A complete pose entry: pose data plus metadata.
    """
    pose: Pose
    metadata: PoseMetadata

    def to_dict(self) -> Dict[str, Any]:
        return {
            "pose": self.pose.to_dict(),
            "metadata": self.metadata.to_dict(),
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> PoseEntry:
        pose = Pose.from_dict(data["pose"])
        metadata = PoseMetadata.from_dict(data["metadata"])
        return cls(pose=pose, metadata=metadata)

    def clone(self) -> PoseEntry:
        return PoseEntry(
            pose=self.pose.clone(),
            metadata=PoseMetadata.from_dict(self.metadata.to_dict())
        )


