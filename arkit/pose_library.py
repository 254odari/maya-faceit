class CategoryTagManager:
    """
    Manage categories and tags in the library.
    """
    def __init__(self, registry: PoseRegistry):
        self._registry = registry

    def get_all_categories(self) -> List[str]:
        categories = set()
        for entry in self._registry.get_all():
            categories.add(entry.metadata.category)
        return sorted(categories)

    def get_all_tags(self) -> List[str]:
        tags = set()
        for entry in self._registry.get_all():
            tags.update(entry.metadata.tags)
        return sorted(tags)

    def get_poses_in_category(self, category: str) -> List[PoseEntry]:
        return [e for e in self._registry.get_all() if e.metadata.category == category]

    def get_poses_with_tag(self, tag: str) -> List[PoseEntry]:
        return [e for e in self._registry.get_all() if tag in e.metadata.tags]

    def add_tag_to_pose(self, identifier: Union[str, Pose], tag: str) -> PoseEntry:
        """Add a tag to a pose."""
        entry = self._get_entry(identifier)
        if tag not in entry.metadata.tags:
            entry.metadata.tags.append(tag)
            entry.metadata.touch()
            self._registry.update(entry)
        return entry

    def remove_tag_from_pose(self, identifier: Union[str, Pose], tag: str) -> PoseEntry:
        entry = self._get_entry(identifier)
        if tag in entry.metadata.tags:
            entry.metadata.tags.remove(tag)
            entry.metadata.touch()
            self._registry.update(entry)
        return entry

    def set_category(self, identifier: Union[str, Pose], category: str) -> PoseEntry:
        entry = self._get_entry(identifier)
        if entry.metadata.category != category:
            entry.metadata.category = category
            entry.metadata.touch()
            self._registry.update(entry)
        return entry

    def _get_entry(self, identifier: Union[str, Pose]) -> PoseEntry:
        if isinstance(identifier, Pose):
            return self._registry.get_by_name(identifier.name)
        elif isinstance(identifier, str):
            if self._registry.exists_id(identifier):
                return self._registry.get_by_id(identifier)
            elif self._registry.exists_name(identifier):
                return self._registry.get_by_name(identifier)
            else:
                raise PoseNotFoundError(f"Pose '{identifier}' not found")
        else:
            raise TypeError("identifier must be str or Pose")


