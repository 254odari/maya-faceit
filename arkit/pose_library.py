class PoseRegistry:
    """
    In-memory registry of all poses, indexed by ID and name.
    """
    def __init__(self):
        self._entries_by_id: Dict[str, PoseEntry] = {}
        self._entries_by_name: Dict[str, PoseEntry] = {}  # name -> entry (assuming unique names)
        self._history: Dict[str, List[PoseHistoryEntry]] = {}  # id -> history
        self._undo_stack: List[Tuple[str, str, PoseEntry]] = []  # (id, action, previous_entry) for undo
        self._redo_stack: List[Tuple[str, str, PoseEntry]] = []  # (id, action, next_entry)

    def add(self, entry: PoseEntry) -> None:
        """Add a new entry. Raises DuplicatePoseError if ID or name exists."""
        if entry.metadata.id in self._entries_by_id:
            raise DuplicatePoseError(f"Pose with ID '{entry.metadata.id}' already exists")
        if entry.metadata.name in self._entries_by_name:
            raise DuplicatePoseError(f"Pose with name '{entry.metadata.name}' already exists")
        self._entries_by_id[entry.metadata.id] = entry
        self._entries_by_name[entry.metadata.name] = entry
        self._history[entry.metadata.id] = []
        # Save initial state in history
        self._history[entry.metadata.id].append(
            PoseHistoryEntry(
                entry=entry.clone(),
                timestamp=datetime.utcnow().isoformat(),
                action="add"
            )
        )
        # Clear undo/redo for this entry
        self._undo_stack = [x for x in self._undo_stack if x[0] != entry.metadata.id]
        self._redo_stack = [x for x in self._redo_stack if x[0] != entry.metadata.id]

    def remove(self, entry_id: str) -> PoseEntry:
        """Remove an entry by ID. Returns the removed entry."""
        if entry_id not in self._entries_by_id:
            raise PoseNotFoundError(f"Pose with ID '{entry_id}' not found")
        entry = self._entries_by_id[entry_id]
        del self._entries_by_id[entry_id]
        del self._entries_by_name[entry.metadata.name]
        # Keep history for possible undo?
        # We'll store deletion as a special undo action.
        self._undo_stack.append((entry_id, "delete", entry.clone()))
        self._redo_stack.clear()
        return entry

    def get_by_id(self, entry_id: str) -> PoseEntry:
        if entry_id not in self._entries_by_id:
            raise PoseNotFoundError(f"Pose with ID '{entry_id}' not found")
        return self._entries_by_id[entry_id]

    def get_by_name(self, name: str) -> PoseEntry:
        if name not in self._entries_by_name:
            raise PoseNotFoundError(f"Pose with name '{name}' not found")
        return self._entries_by_name[name]

    def get_all(self) -> List[PoseEntry]:
        return list(self._entries_by_id.values())

    def get_ids(self) -> List[str]:
        return list(self._entries_by_id.keys())

    def get_names(self) -> List[str]:
        return list(self._entries_by_name.keys())

    def update(self, entry: PoseEntry) -> None:
        """Update an existing entry. Raises PoseNotFoundError if ID missing."""
        if entry.metadata.id not in self._entries_by_id:
            raise PoseNotFoundError(f"Pose with ID '{entry.metadata.id}' not found")
        old_name = self._entries_by_id[entry.metadata.id].metadata.name
        # Check name uniqueness if changed
        if old_name != entry.metadata.name and entry.metadata.name in self._entries_by_name:
            raise DuplicatePoseError(f"Pose with name '{entry.metadata.name}' already exists")
        # Save old entry for undo
        old_entry = self._entries_by_id[entry.metadata.id].clone()
        # Update
        self._entries_by_id[entry.metadata.id] = entry
        if old_name != entry.metadata.name:
            del self._entries_by_name[old_name]
            self._entries_by_name[entry.metadata.name] = entry
        # Add to undo stack
        self._undo_stack.append((entry.metadata.id, "update", old_entry))
        self._redo_stack.clear()
        # Update history
        self._history[entry.metadata.id].append(
            PoseHistoryEntry(
                entry=entry.clone(),
                timestamp=datetime.utcnow().isoformat(),
                action="update"
            )
        )

    def exists_id(self, entry_id: str) -> bool:
        return entry_id in self._entries_by_id

    def exists_name(self, name: str) -> bool:
        return name in self._entries_by_name

    def history(self, entry_id: str) -> List[PoseHistoryEntry]:
        if entry_id not in self._history:
            return []
        return self._history[entry_id]

    def undo(self) -> Optional[PoseEntry]:
        """Undo the last operation. Returns the restored entry."""
        if not self._undo_stack:
            return None
        action_id, action, entry = self._undo_stack.pop()
        # Restore entry
        if action == "delete":
            # Re-add
            self.add(entry)
            restored = entry
        elif action == "update":
            # Restore old entry (which is stored)
            current = self._entries_by_id[entry.metadata.id]
            self._redo_stack.append((entry.metadata.id, "update", current))
            self._entries_by_id[entry.metadata.id] = entry
            self._entries_by_name[entry.metadata.name] = entry
            restored = entry
        else:
            return None
        # Add to redo stack
        self._redo_stack.append((action_id, action, entry))
        return restored

    def redo(self) -> Optional[PoseEntry]:
        """Redo the last undone operation."""
        if not self._redo_stack:
            return None
        action_id, action, entry = self._redo_stack.pop()
        if action == "delete":
            # Remove again
            self.remove(entry.metadata.id)
            return None
        elif action == "update":
            # Apply the update (entry is the new state)
            current = self._entries_by_id[entry.metadata.id]
            self._undo_stack.append((entry.metadata.id, "update", current))
            self._entries_by_id[entry.metadata.id] = entry
            self._entries_by_name[entry.metadata.name] = entry
            return entry
        return None


# ---- Part 4: CRUD Operations ------------------------------------------

class CRUDEngine:
    """
    Implements Create, Read, Update, Delete operations on the registry.
    """
    def __init__(self, registry: PoseRegistry, validator: Optional[ARKitValidator] = None):
        self._registry = registry
        self._validator = validator or ARKitValidator()

    def add_pose(
        self,
        pose: Pose,
        name: Optional[str] = None,
        author: str = "unknown",
        tags: Optional[List[str]] = None,
        category: str = "Uncategorized",
        favorite: bool = False,
        source: str = "user",
        notes: str = "",
        validate: bool = True,
    ) -> PoseEntry:
        """Create a new pose entry and add it to the library."""
        if validate:
            report = self._validator.validate_coefficients(
                pose.coefficients,
                level=ValidationLevel.STANDARD if ValidationLevel else None,
                allow_extra_channels=True
            )
            if not report.is_valid:
                raise InvalidPoseError(f"Pose validation failed: {', '.join(e.message for e in report.errors)}")

        # Generate ID
        pose_id = str(uuid.uuid4())
        now = datetime.utcnow().isoformat()
        name_to_use = name if name is not None else pose.name
        if not name_to_use:
            name_to_use = "Unnamed"
        # Ensure unique name: if exists, append number
        base_name = name_to_use
        counter = 1
        while self._registry.exists_name(name_to_use):
            name_to_use = f"{base_name}_{counter}"
            counter += 1

        metadata = PoseMetadata(
            id=pose_id,
            name=name_to_use,
            created=now,
            modified=now,
            author=author,
            tags=tags or [],
            category=category,
            favorite=favorite,
            version=1,
            source=source,
            notes=notes,
        )
        entry = PoseEntry(pose=pose, metadata=metadata)
        self._registry.add(entry)
        return entry

    def get_pose(self, identifier: Union[str, Pose]) -> PoseEntry:
        """Retrieve a pose by ID, name, or by matching pose object."""
        if isinstance(identifier, Pose):
            # Try to find by name first, then by comparing coefficients?
            # For simplicity, we assume name is unique.
            return self._registry.get_by_name(identifier.name)
        elif isinstance(identifier, str):
            # Try as ID first, then as name
            if self._registry.exists_id(identifier):
                return self._registry.get_by_id(identifier)
            elif self._registry.exists_name(identifier):
                return self._registry.get_by_name(identifier)
            else:
                raise PoseNotFoundError(f"Pose '{identifier}' not found")
        else:
            raise TypeError("identifier must be str or Pose")

    def remove_pose(self, identifier: Union[str, Pose]) -> PoseEntry:
        """Remove a pose by ID or name."""
        entry = self.get_pose(identifier)
        return self._registry.remove(entry.metadata.id)

    def update_pose(
        self,
        identifier: Union[str, Pose],
        new_pose: Optional[Pose] = None,
        new_name: Optional[str] = None,
        new_author: Optional[str] = None,
        new_tags: Optional[List[str]] = None,
        new_category: Optional[str] = None,
        new_favorite: Optional[bool] = None,
        new_notes: Optional[str] = None,
        validate: bool = True,
    ) -> PoseEntry:
        """Update an existing pose's data and/or metadata."""
        entry = self.get_pose(identifier)
        old_entry = entry.clone()

        # Update pose if provided
        if new_pose is not None:
            if validate:
                report = self._validator.validate_coefficients(
                    new_pose.coefficients,
                    level=ValidationLevel.STANDARD if ValidationLevel else None,
                    allow_extra_channels=True
                )
                if not report.is_valid:
                    raise InvalidPoseError(f"Pose validation failed: {', '.join(e.message for e in report.errors)}")
            entry.pose = new_pose

        # Update metadata
        metadata = entry.metadata
        if new_name is not None:
            # Check uniqueness if changed
            if new_name != metadata.name and self._registry.exists_name(new_name):
                raise DuplicatePoseError(f"Pose with name '{new_name}' already exists")
            metadata.name = new_name
        if new_author is not None:
            metadata.author = new_author
        if new_tags is not None:
            metadata.tags = new_tags
        if new_category is not None:
            metadata.category = new_category
        if new_favorite is not None:
            metadata.favorite = new_favorite
        if new_notes is not None:
            metadata.notes = new_notes
        metadata.touch()

        # Apply update to registry
        self._registry.update(entry)
        return entry

    def rename_pose(self, identifier: Union[str, Pose], new_name: str) -> PoseEntry:
        """Rename a pose."""
        return self.update_pose(identifier, new_name=new_name)

    def duplicate_pose(self, identifier: Union[str, Pose], new_name: Optional[str] = None) -> PoseEntry:
        """Duplicate a pose with a new name."""
        entry = self.get_pose(identifier)
        if new_name is None:
            new_name = f"{entry.metadata.name}_copy"
        # Make a copy of the pose
        new_pose = entry.pose.clone()
        # Generate new ID and metadata
        now = datetime.utcnow().isoformat()
        new_id = str(uuid.uuid4())
        # Ensure unique name
        base = new_name
        counter = 1
        while self._registry.exists_name(new_name):
            new_name = f"{base}_{counter}"
            counter += 1
        new_metadata = PoseMetadata(
            id=new_id,
            name=new_name,
            created=now,
            modified=now,
            author=entry.metadata.author,
            tags=entry.metadata.tags.copy(),
            category=entry.metadata.category,
            favorite=False,
            version=1,
            source=entry.metadata.source,
            notes=f"Duplicate of {entry.metadata.name}",
        )
        new_entry = PoseEntry(pose=new_pose, metadata=new_metadata)
        self._registry.add(new_entry)
        return new_entry

    def replace_pose(self, identifier: Union[str, Pose], new_pose: Pose) -> PoseEntry:
        """Replace the pose data of an existing entry, keeping metadata."""
        return self.update_pose(identifier, new_pose=new_pose)


