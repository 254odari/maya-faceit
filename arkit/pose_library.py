class SerializationEngine:
    """
    Handles serialization to/from various formats and file I/O.
    """
    @staticmethod
    def serialize_json(entry: PoseEntry) -> str:
        """Serialize a single PoseEntry to JSON string."""
        return json.dumps(entry.to_dict(), indent=2)

    @staticmethod
    def deserialize_json(data: str) -> PoseEntry:
        """Deserialize a PoseEntry from JSON string."""
        try:
            obj = json.loads(data)
            return PoseEntry.from_dict(obj)
        except json.JSONDecodeError as e:
            raise SerializationError(f"Invalid JSON: {e}")

    @staticmethod
    def serialize_yaml(entry: PoseEntry) -> str:
        """Serialize to YAML (if available)."""
        if not HAS_YAML:
            raise SerializationError("PyYAML not installed")
        return yaml.dump(entry.to_dict(), default_flow_style=False)

    @staticmethod
    def deserialize_yaml(data: str) -> PoseEntry:
        if not HAS_YAML:
            raise SerializationError("PyYAML not installed")
        try:
            obj = yaml.safe_load(data)
            return PoseEntry.from_dict(obj)
        except yaml.YAMLError as e:
            raise SerializationError(f"Invalid YAML: {e}")

    @staticmethod
    def export_library(entries: List[PoseEntry], filepath: str, format: str = "json") -> None:
        """Export a list of entries to a file."""
        data = [e.to_dict() for e in entries]
        if format == "json":
            with open(filepath, 'w', encoding='utf-8') as f:
                json.dump(data, f, indent=2, ensure_ascii=False)
        elif format == "yaml" and HAS_YAML:
            with open(filepath, 'w', encoding='utf-8') as f:
                yaml.dump(data, f, default_flow_style=False)
        else:
            raise SerializationError(f"Unsupported or unavailable format: {format}")

    @staticmethod
    def import_library(filepath: str, format: str = "json") -> List[PoseEntry]:
        """Import a list of entries from a file."""
        if format == "json":
            with open(filepath, 'r', encoding='utf-8') as f:
                data = json.load(f)
            return [PoseEntry.from_dict(item) for item in data]
        elif format == "yaml" and HAS_YAML:
            with open(filepath, 'r', encoding='utf-8') as f:
                data = yaml.safe_load(f)
            return [PoseEntry.from_dict(item) for item in data]
        else:
            raise SerializationError(f"Unsupported or unavailable format: {format}")

    @staticmethod
    def save_entry_to_file(entry: PoseEntry, directory: str, format: str = "json") -> str:
        """Save a single entry as a file in the given directory."""
        os.makedirs(directory, exist_ok=True)
        filename = f"{entry.metadata.id}.{format}"
        filepath = os.path.join(directory, filename)
        data = entry.to_dict()
        if format == "json":
            with open(filepath, 'w', encoding='utf-8') as f:
                json.dump(data, f, indent=2, ensure_ascii=False)
        elif format == "yaml" and HAS_YAML:
            with open(filepath, 'w', encoding='utf-8') as f:
                yaml.dump(data, f, default_flow_style=False)
        else:
            raise SerializationError(f"Unsupported format: {format}")
        return filepath

    @staticmethod
    def load_entry_from_file(filepath: str) -> PoseEntry:
        """Load a single entry from a file (detect format by extension)."""
        ext = os.path.splitext(filepath)[1].lower()
        if ext in ['.json']:
            with open(filepath, 'r', encoding='utf-8') as f:
                data = json.load(f)
            return PoseEntry.from_dict(data)
        elif ext in ['.yaml', '.yml'] and HAS_YAML:
            with open(filepath, 'r', encoding='utf-8') as f:
                data = yaml.safe_load(f)
            return PoseEntry.from_dict(data)
        else:
            raise SerializationError(f"Unsupported file type: {ext}")

    @staticmethod
    def load_directory(directory: str, recursive: bool = True) -> List[PoseEntry]:
        """Load all pose files from a directory."""
        entries = []
        for root, dirs, files in os.walk(directory) if recursive else [(directory, [], os.listdir(directory))]:
            for file in files:
                if file.endswith(('.json', '.yaml', '.yml')):
                    try:
                        entry = SerializationEngine.load_entry_from_file(os.path.join(root, file))
                        entries.append(entry)
                    except Exception as e:
                        logger.warning(f"Failed to load {file}: {e}")
        return entries


# ---- Part 8: Versioning & History -------------------------------------

class VersioningEngine:
    """
    Manages version history per pose.
    """
    def __init__(self, registry: PoseRegistry):
        self._registry = registry

    def get_history(self, identifier: Union[str, Pose]) -> List[PoseHistoryEntry]:
        entry = self._get_entry(identifier)
        return self._registry.history(entry.metadata.id)

    def rollback(self, identifier: Union[str, Pose], version: int) -> PoseEntry:
        """Rollback a pose to a specific version number."""
        entry = self._get_entry(identifier)
        history = self._registry.history(entry.metadata.id)
        if not history:
            raise ARKitPoseLibraryError(f"No history for pose '{entry.metadata.name}'")
        # Find the entry with that version
        # Versions start at 1; history entries might have version numbers
        # We'll use the version field in metadata, but history stores snapshots.
        # We'll find the snapshot that corresponds to the version.
        # Since we increment version on each update, we can search.
        target = None
        for h in history:
            if h.entry.metadata.version == version:
                target = h.entry
                break
        if target is None:
            raise ARKitPoseLibraryError(f"Version {version} not found for pose '{entry.metadata.name}'")
        # Replace current entry with target
        new_entry = target.clone()
        # Ensure we don't duplicate ID; we keep same ID.
        new_entry.metadata.id = entry.metadata.id
        # Update modified timestamp and version
        new_entry.metadata.touch()
        self._registry.update(new_entry)
        return new_entry

    def _get_entry(self, identifier: Union[str, Pose]) -> PoseEntry:
        if isinstance(identifier, Pose):
            return self._registry.get_by_name(identifier.name)
        elif isinstance(identifier, str):
            if self._registry.exists_id(identifier):
                return self._registry.get_by_id(identifier)
            elif self._registry.exists_name(identifier):
                return self._registry.get_by_name(identifier)
            else:
                raise PoseNotFoundError(f"Pose '{identifier}' not found")
        else:
            raise TypeError("identifier must be str or Pose")


# ---- Part 9: Diagnostics ---------------------------------------------

class DiagnosticsEngine:
    """
    Generates diagnostic reports for the library.
    """
    def __init__(self, registry: PoseRegistry, validator: Optional[ARKitValidator] = None):
        self._registry = registry
        self._validator = validator or ARKitValidator()

    def diagnose(self) -> LibraryDiagnostics:
        diag = LibraryDiagnostics(is_valid=True)
        names = set()
        ids = set()
        all_channels = set()
        for entry in self._registry.get_all():
            # Check duplicate names
            if entry.metadata.name in names:
                diag.duplicate_names.append(entry.metadata.name)
                diag.warnings.append(f"Duplicate name: '{entry.metadata.name}'")
            names.add(entry.metadata.name)

            # Check duplicate IDs
            if entry.metadata.id in ids:
                diag.corrupt_entries.append(entry.metadata.id)
                diag.errors.append(f"Duplicate ID: '{entry.metadata.id}'")
            ids.add(entry.metadata.id)

            # Validate coefficients
            report = self._validator.validate_coefficients(
                entry.pose.coefficients,
                level=ValidationLevel.STANDARD if ValidationLevel else None,
                allow_extra_channels=True
            )
            if not report.is_valid:
                diag.errors.extend([f"Pose '{entry.metadata.name}': {e.message}" for e in report.errors])
                diag.is_valid = False
            for warn in report.warnings:
                diag.warnings.append(f"Pose '{entry.metadata.name}': {warn.message}")

            # Check for unknown channels (not in ARKIT_SET)
            if ARKIT_SET:
                for ch in entry.pose.coefficients:
                    if ch not in ARKIT_SET and ch not in diag.missing_channels:
                        diag.missing_channels.append(ch)
                        diag.warnings.append(f"Pose '{entry.metadata.name}' uses unknown channel '{ch}'")

        if diag.errors:
            diag.is_valid = False
        return diag


# ---- Part 10: Statistics ---------------------------------------------

class StatisticsEngine:
    """
    Computes statistics about the library.
    """
    def __init__(self, registry: PoseRegistry):
        self._registry = registry

    def compute_statistics(self, disk_path: Optional[str] = None) -> LibraryStatistics:
        entries = self._registry.get_all()
        stats = LibraryStatistics()
        stats.total_poses = len(entries)
        stats.builtin_count = sum(1 for e in entries if e.metadata.source == "builtin")
        stats.user_count = stats.total_poses - stats.builtin_count
        stats.favorite_count = sum(1 for e in entries if e.metadata.favorite)

        categories = {}
        tags = {}
        authors = {}
        total_channels = 0
        max_channels = 0
        for entry in entries:
            cat = entry.metadata.category
            categories[cat] = categories.get(cat, 0) + 1
            for tag in entry.metadata.tags:
                tags[tag] = tags.get(tag, 0) + 1
            author = entry.metadata.author
            authors[author] = authors.get(author, 0) + 1
            ch_count = len(entry.pose.coefficients)
            total_channels += ch_count
            if ch_count > max_channels:
                max_channels = ch_count

        stats.categories = categories
        stats.tags = tags
        stats.authors = authors
        stats.max_channels = max_channels
        stats.average_channels = total_channels / stats.total_poses if stats.total_poses > 0 else 0.0
        stats.total_coefficients = total_channels

        if disk_path and os.path.exists(disk_path):
            # Compute disk size
            total_size = 0
            if os.path.isdir(disk_path):
                for root, dirs, files in os.walk(disk_path):
                    for f in files:
                        fp = os.path.join(root, f)
                        total_size += os.path.getsize(fp)
            else:
                total_size = os.path.getsize(disk_path)
            stats.disk_size_bytes = total_size

        # Last modified: take max of modified timestamps
        if entries:
            last_mod = max(e.metadata.modified for e in entries)
            stats.last_modified = last_mod

        return stats


# ---- Part 11: Public API -----------------------------------------------

class PoseLibrary:
    """
    The main pose library class providing all management functionality.

    Methods:
        load(): Load library from disk.
        save(): Save library to disk.
        add(): Add a new pose.
        get(): Retrieve a pose.
        remove(): Delete a pose.
        update(): Update a pose.
        rename(): Rename a pose.
        duplicate(): Duplicate a pose.
        replace(): Replace a pose's data.
        search(): Search for poses.
        filter(): Filter poses.
        favorite(): Mark/unmark as favorite.
        add_tag(): Add a tag to a pose.
        remove_tag(): Remove a tag from a pose.
        set_category(): Set category for a pose.
        get_categories(): List all categories.
        get_tags(): List all tags.
        export(): Export library to a file.
        import_library(): Import from a file.
        undo(): Undo last operation.
        redo(): Redo last operation.
        history(): Get history of a pose.
        rollback(): Rollback to a version.
        statistics(): Get library statistics.
        diagnostics(): Get diagnostic report.
        clear(): Clear all user poses (built-in remain).
    """
    def __init__(
        self,
        root_path: Optional[str] = None,
        builtin_path: Optional[str] = None,
        load_on_init: bool = True,
        use_validator: bool = True,
    ):
        """
        Args:
            root_path: Path to the library directory (user poses).
            builtin_path: Path to built-in poses (read-only). If None, uses default built-ins.
            load_on_init: If True, load poses from root_path and builtin_path.
            use_validator: If True, validate poses.
        """
        self._root_path = root_path
        self._builtin_path = builtin_path
        self._use_validator = use_validator
        self._registry = PoseRegistry()
        self._validator = ARKitValidator() if use_validator else None
        self._crud = CRUDEngine(self._registry, self._validator)
        self._search = SearchEngine(self._registry)
        self._category_tag = CategoryTagManager(self._registry)
        self._versioning = VersioningEngine(self._registry)
        self._diagnostics = DiagnosticsEngine(self._registry, self._validator)
        self._statistics = StatisticsEngine(self._registry)

        self._builtin_loaded = False
        self._user_loaded = False

        # Track if there are unsaved changes
        self._dirty = False

        if load_on_init:
            self.load()

    # --- Loading / Saving ---

    def load(self, root_path: Optional[str] = None, builtin_path: Optional[str] = None) -> None:
        """
        Load poses from the library directories.
        If paths are None, use the ones from initialization.
        """
        if root_path is not None:
            self._root_path = root_path
        if builtin_path is not None:
            self._builtin_path = builtin_path

        # Clear existing registry (keep only built-in if we want to reload)
        # We'll clear all and reload
        self._registry = PoseRegistry()
        self._builtin_loaded = False
        self._user_loaded = False

        # Load built-in
        if self._builtin_path:
            self._load_builtin_from_path(self._builtin_path)
        else:
            # Load default built-in poses from generator
            self._load_default_builtin()

        # Load user poses
        if self._root_path:
            self._load_user_from_path(self._root_path)

        self._dirty = False
        logger.info(f"Library loaded: {len(self._registry.get_all())} poses")

    def save(self, root_path: Optional[str] = None) -> None:
        """
        Save all user poses to disk.
        If root_path not provided, uses the current root_path.
        If root_path is None and no root_path set, raises error.
        """
        if root_path is not None:
            self._root_path = root_path
        if not self._root_path:
            raise LibraryLoadError("No root path set for saving")

        # Save each user pose as a separate file
        # We'll only save user poses (source == "user")
        user_entries = [e for e in self._registry.get_all() if e.metadata.source == "user"]
        if not user_entries:
            logger.info("No user poses to save")
            return

        os.makedirs(self._root_path, exist_ok=True)
        for entry in user_entries:
            SerializationEngine.save_entry_to_file(entry, self._root_path, format="json")

        self._dirty = False
        logger.info(f"Saved {len(user_entries)} user poses to {self._root_path}")

    def clear(self) -> None:
        """Remove all user poses from the library (built-in remain)."""
        # Collect user IDs
        to_remove = [e.metadata.id for e in self._registry.get_all() if e.metadata.source == "user"]
        for eid in to_remove:
            self._registry.remove(eid)
        self._dirty = True

    # --- Internal loading helpers ---

    def _load_default_builtin(self) -> None:
        """Load built-in poses from the built-in generator."""
        try:
            from .pose_generator import ExpressionEngine
            # Generate default expressions
            expressions = [
                "Neutral", "Smile", "SmileLeft", "SmileRight",
                "Blink", "WinkLeft", "WinkRight",
                "Surprise", "Anger", "Sad", "Disgust", "Fear", "Joy",
                "Viseme_AH", "Viseme_EE", "Viseme_OH", "Viseme_OO", "Viseme_FF"
            ]
            for expr in expressions:
                try:
                    pose = ExpressionEngine.generate(expr, intensity=1.0)
                    # Add as built-in
                    entry = self._crud.add_pose(
                        pose,
                        name=expr,
                        author="builtin",
                        tags=["builtin", "expression"],
                        category="Builtin",
                        source="builtin",
                        validate=self._use_validator
                    )
                    # Mark as builtin (already source="builtin")
                except Exception as e:
                    logger.warning(f"Failed to generate built-in pose '{expr}': {e}")
            self._builtin_loaded = True
            logger.info(f"Loaded {len(expressions)} built-in poses")
        except ImportError:
            logger.warning("pose_generator not available; no built-in poses loaded")

    def _load_builtin_from_path(self, path: str) -> None:
        """Load built-in poses from a directory."""
        if not os.path.exists(path):
            logger.warning(f"Built-in path '{path}' does not exist")
            return
        entries = SerializationEngine.load_directory(path)
        for entry in entries:
            # Ensure source is "builtin"
            entry.metadata.source = "builtin"
            try:
                self._registry.add(entry)
            except DuplicatePoseError:
                logger.warning(f"Skipping duplicate built-in pose: {entry.metadata.name}")
        self._builtin_loaded = True
        logger.info(f"Loaded {len(entries)} built-in poses from {path}")

    def _load_user_from_path(self, path: str) -> None:
        """Load user poses from a directory."""
        if not os.path.exists(path):
            logger.info(f"User path '{path}' does not exist, creating")
            os.makedirs(path, exist_ok=True)
            return
        entries = SerializationEngine.load_directory(path)
        for entry in entries:
            entry.metadata.source = "user"
            try:
                self._registry.add(entry)
            except DuplicatePoseError:
                logger.warning(f"Skipping duplicate user pose: {entry.metadata.name}")
        self._user_loaded = True
        logger.info(f"Loaded {len(entries)} user poses from {path}")

    # --- CRUD Operations ---

    def add(
        self,
        pose: Pose,
        name: Optional[str] = None,
        author: str = "unknown",
        tags: Optional[List[str]] = None,
        category: str = "Uncategorized",
        favorite: bool = False,
        notes: str = "",
        validate: bool = True,
    ) -> PoseEntry:
        """Add a new pose to the library."""
        entry = self._crud.add_pose(
            pose, name, author, tags, category, favorite,
            source="user", notes=notes, validate=validate and self._use_validator
        )
        self._dirty = True
        return entry

    def get(self, identifier: Union[str, Pose]) -> PoseEntry:
        """Retrieve a pose by ID or name."""
        return self._crud.get_pose(identifier)

    def remove(self, identifier: Union[str, Pose]) -> PoseEntry:
        """Remove a pose. Built-in poses cannot be removed."""
        entry = self.get(identifier)
        if entry.metadata.source == "builtin":
            raise ARKitPoseLibraryError("Cannot remove built-in poses")
        removed = self._crud.remove_pose(identifier)
        self._dirty = True
        return removed

    def update(
        self,
        identifier: Union[str, Pose],
        new_pose: Optional[Pose] = None,
        new_name: Optional[str] = None,
        new_author: Optional[str] = None,
        new_tags: Optional[List[str]] = None,
        new_category: Optional[str] = None,
        new_favorite: Optional[bool] = None,
        new_notes: Optional[str] = None,
        validate: bool = True,
    ) -> PoseEntry:
        """Update a pose."""
        entry = self._crud.update_pose(
            identifier, new_pose, new_name, new_author, new_tags,
            new_category, new_favorite, new_notes,
            validate=validate and self._use_validator
        )
        self._dirty = True
        return entry

    def rename(self, identifier: Union[str, Pose], new_name: str) -> PoseEntry:
        return self.update(identifier, new_name=new_name)

    def duplicate(self, identifier: Union[str, Pose], new_name: Optional[str] = None) -> PoseEntry:
        entry = self._crud.duplicate_pose(identifier, new_name)
        self._dirty = True
        return entry

    def replace(self, identifier: Union[str, Pose], new_pose: Pose) -> PoseEntry:
        entry = self._crud.replace_pose(identifier, new_pose)
        self._dirty = True
        return entry

    # --- Search and Filtering ---

    def search(self, query: str) -> List[PoseEntry]:
        return self._search.search(query)

    def filter_by_tags(self, tags: List[str], match_all: bool = True) -> List[PoseEntry]:
        return self._search.filter_by_tags(tags, match_all)

    def filter_by_category(self, category: str) -> List[PoseEntry]:
        return self._search.filter_by_category(category)

    def filter_by_author(self, author: str) -> List[PoseEntry]:
        return self._search.filter_by_author(author)

    def filter_by_channels(self, channels: List[str], min_value: float = 0.01) -> List[PoseEntry]:
        return self._search.filter_by_channels(channels, min_value)

    def filter_by_favorite(self) -> List[PoseEntry]:
        return self._search.filter_by_favorite()

    def filter_by_source(self, source: str) -> List[PoseEntry]:
        return self._search.filter_by_source(source)

    def filter_by_date_range(self, start: Optional[str] = None, end: Optional[str] = None) -> List[PoseEntry]:
        return self._search.filter_by_date_range(start, end)

    # --- Categories and Tags ---

    def get_all_categories(self) -> List[str]:
        return self._category_tag.get_all_categories()

    def get_all_tags(self) -> List[str]:
        return self._category_tag.get_all_tags()

    def add_tag(self, identifier: Union[str, Pose], tag: str) -> PoseEntry:
        entry = self._category_tag.add_tag_to_pose(identifier, tag)
        self._dirty = True
        return entry

    def remove_tag(self, identifier: Union[str, Pose], tag: str) -> PoseEntry:
        entry = self._category_tag.remove_tag_from_pose(identifier, tag)
        self._dirty = True
        return entry

    def set_category(self, identifier: Union[str, Pose], category: str) -> PoseEntry:
        entry = self._category_tag.set_category(identifier, category)
        self._dirty = True
        return entry

    def favorite(self, identifier: Union[str, Pose], flag: bool = True) -> PoseEntry:
        return self.update(identifier, new_favorite=flag)

    # --- Import / Export ---

    def export_all(self, filepath: str, format: str = "json") -> None:
        """Export all poses to a single file."""
        entries = self._registry.get_all()
        SerializationEngine.export_library(entries, filepath, format)

    def export_user(self, filepath: str, format: str = "json") -> None:
        """Export only user poses."""
        entries = [e for e in self._registry.get_all() if e.metadata.source == "user"]
        SerializationEngine.export_library(entries, filepath, format)

    def import_library(self, filepath: str, format: str = "json", source: str = "user") -> List[PoseEntry]:
        """Import poses from a file."""
        entries = SerializationEngine.import_library(filepath, format)
        imported = []
        for entry in entries:
            # Ensure source is set
            entry.metadata.source = source
            try:
                self._registry.add(entry)
                imported.append(entry)
            except DuplicatePoseError:
                logger.warning(f"Skipping duplicate pose: {entry.metadata.name}")
        self._dirty = True
        return imported

    # --- Versioning ---

    def get_history(self, identifier: Union[str, Pose]) -> List[PoseHistoryEntry]:
        return self._versioning.get_history(identifier)

    def rollback(self, identifier: Union[str, Pose], version: int) -> PoseEntry:
        entry = self._versioning.rollback(identifier, version)
        self._dirty = True
        return entry

    def undo(self) -> Optional[PoseEntry]:
        """Undo the last operation globally."""
        entry = self._registry.undo()
        if entry:
            self._dirty = True
        return entry

    def redo(self) -> Optional[PoseEntry]:
        """Redo the last undone operation."""
        entry = self._registry.redo()
        if entry:
            self._dirty = True
        return entry

    # --- Diagnostics and Statistics ---

    def diagnostics(self) -> LibraryDiagnostics:
        return self._diagnostics.diagnose()

    def statistics(self, disk_path: Optional[str] = None) -> LibraryStatistics:
        # Use root path if not provided
        if disk_path is None:
            disk_path = self._root_path
        return self._statistics.compute_statistics(disk_path)

    # --- Utility ---

    def list_poses(self) -> List[PoseEntry]:
        """Return all poses."""
        return self._registry.get_all()

    def is_dirty(self) -> bool:
        return self._dirty

    def get_builtin_count(self) -> int:
        return sum(1 for e in self._registry.get_all() if e.metadata.source == "builtin")

    def get_user_count(self) -> int:
        return sum(1 for e in self._registry.get_all() if e.metadata.source == "user")


